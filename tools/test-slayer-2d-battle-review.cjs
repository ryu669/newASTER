const assert=require('node:assert/strict'),path=require('node:path'),fs=require('node:fs');
const {pathToFileURL}=require('node:url');
if(!process.env.SLAYER_PLAYWRIGHT_MODULE)throw Error('Set SLAYER_PLAYWRIGHT_MODULE to an installed playwright module');
const {chromium}=require(process.env.SLAYER_PLAYWRIGHT_MODULE);
const root=path.resolve(__dirname,'..');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1600,height:1100}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.join(root,'game/art-source/slayer/slayer-2d-battle-review.html')).href);
  await page.waitForFunction(()=>[...document.images].every(i=>i.complete&&i.naturalWidth>0));
  assert.equal(await page.locator('.member').count(),5);
  const hp=()=>page.locator('.member small').allTextContents();
  const initial=await hp();
  const output=path.join(root,'game/Builds/battle-2d-review');fs.mkdirSync(output,{recursive:true});
  await page.screenshot({path:path.join(output,'portrait-1600.png'),fullPage:true});
  await page.getByRole('button',{name:'全身5人',exact:true}).click();
  await page.screenshot({path:path.join(output,'fullbody-1600.png'),fullPage:true});
  await page.locator('#count').selectOption('3');
  await page.locator('#heal').click();
  await page.waitForTimeout(180);
  await page.locator('#pause').click();
  const frozen=await hp();await page.waitForTimeout(400);assert.deepEqual(await hp(),frozen);
  await page.locator('#pause').click();
  await page.waitForFunction(()=>!document.getElementById('heal').disabled);
  const healed=await hp();
  assert.deepEqual(healed,['HP 820 / 1000','HP 610 / 1000','HP 790 / 1000','HP 440 / 1000','HP 880 / 1000']);
  assert.equal(healed.filter((v,i)=>v!==initial[i]).length,3);
  await page.locator('#reset').click();
  await page.locator('.member').nth(4).click();
  await page.locator('#count').selectOption('1');await page.locator('#heal').click();
  await page.waitForFunction(()=>!document.getElementById('heal').disabled);
  assert.deepEqual(await hp(),['HP 640 / 1000','HP 430 / 1000','HP 790 / 1000','HP 260 / 1000','HP 1000 / 1000']);
  await page.locator('#reset').click();await page.locator('#enemy-hit').click();
  await page.waitForFunction(()=>!document.getElementById('enemy-hit').disabled);
  assert.deepEqual(await hp(),['HP 520 / 1000','HP 310 / 1000','HP 670 / 1000','HP 140 / 1000','HP 760 / 1000']);
  await page.locator('#reset').click();await page.locator('#count').selectOption('5');await page.locator('#heal').click();
  await page.waitForFunction(()=>!document.getElementById('heal').disabled);
  assert.equal((await hp()).filter((v,i)=>v!==initial[i]).length,5);
  await page.locator('#reset').click();await page.locator('[data-part="左翼"]').click();await page.locator('#attack').click();
  assert.match(await page.locator('#action-label').textContent(),/左翼/);
  await page.waitForFunction(()=>!document.getElementById('attack').disabled);
  assert.deepEqual(await hp(),initial);
  await page.getByRole('button',{name:'顔重視',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(output,'portrait-390.png'),fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390);
  assert.deepEqual(errors,[]);
  console.log('BATTLE_REVIEW_PASS: 5 slots, 1/3/5 heal targets, pause/resume, reset, all-party hit, selected part, image loading, 390px width; no page errors');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
